import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { loadSession, createContext, PROOFS_ROOT } from '/Users/SaintNick/Documents/Cortex/Project-Cortex-Proofs/sandbox-env/runner.mjs';
import { verifyCloud, getDeployKey } from '/Users/SaintNick/Documents/Cortex/Project-Cortex-Proofs/sandbox-env/cloud.mjs';
const qa = path.dirname(new URL(import.meta.url).pathname);
const sessionId = process.argv[2];
assert.match(sessionId ?? '', /^[a-f0-9]{8}(?:-[a-f0-9]{4}){3}-[a-f0-9]{12}$/);
const session = await loadSession(PROOFS_ROOT, sessionId);
assert.equal(session.phase, 'READY');
assert.ok(Number.isSafeInteger(session.target.id) && session.target.id > 0);
assert.match(session.target.name, /^[a-z]+(?:-[a-z]+)+-\d+$/);
assert.equal(session.target.teamId, 325340);
assert.equal(session.target.projectId, 3200658);
assert.equal(session.target.isDefault, false);
assert.equal(session.target.reference, 'dev/cortex-sandbox-' + sessionId);
assert.equal(session.target.deploymentType, 'dev');
assert.ok(session.target.serverExpiryVerified && session.target.expiresAt > Date.now());
const kit = path.join(PROOFS_ROOT, 'manual-sandbox-managed-source-2026-10-14');
const manifestRaw = await fs.readFile(path.join(kit, 'image/archives/manifest.json'));
const manifest = JSON.parse(manifestRaw);
const sha = value => createHash('sha256').update(value).digest('hex');
assert.equal(manifest.sourceCommit, '9fb9687536af0b7abfcb7280e0aa26ef450051ea');
assert.equal(manifest.backend.files, 170);
const prepared = JSON.parse(await fs.readFile(path.join(session.receiptDir, 'host-prepared.json')));
assert.equal(prepared.sourceCommit, manifest.sourceCommit);
assert.equal(session.container.imageId, (await fs.readFile(path.join(kit,'image-id.txt'),'utf8')).trim());
assert.equal(session.cloudIntent.requestedRegion,'aws-us-east-1');
const ctx = await createContext(session, { logger: () => {} });
await verifyCloud(session, ctx);
const key = await getDeployKey(session, ctx);
const cli = path.join(session.backendDir, 'node_modules/convex/bin/main.js');
const options = { cwd: session.backendDir, env: { CONVEX_DEPLOY_KEY: key, CONVEX_DEPLOYMENT: 'dev:' + session.target.name }, timeoutMs: 30000 };
await ctx.command('k26-enable-backend-trace', ctx.node, [cli, 'env', 'set', 'CORTEX_RUNTIME_LATENCY_TRACE', '1'], options);
await verifyCloud(session, ctx);
const result = await ctx.command('k26-verify-backend-trace', ctx.node, [cli, 'env', 'get', 'CORTEX_RUNTIME_LATENCY_TRACE'], options);
assert.equal(result.stdout.trim(), '1');
const pins = { ready: true, sessionId, name: session.target.name, targetId: session.target.id, expiresAt: session.target.expiresAt, imageId: session.container.imageId, sourceCommit: manifest.sourceCommit, kit, backendManifestSha256: manifest.backend.manifestSha256, manifestSha256: sha(manifestRaw), sdkArchiveSha256: manifest.packages.find(row => row.role === 'sdk').sha256, runIds: ['UNREADY','UNREADY','UNREADY','UNREADY'], markers: ['READY46', 'WARM46', 'CLI46', 'CLW46'], toolMarker:'TOOL46', toolRunId:'UNREADY' };
const pinFile = path.join(qa, 'k26-collector-pins.mjs');
let source = await fs.readFile(pinFile, 'utf8');
const start = source.indexOf('Object.freeze(') + 'Object.freeze('.length;
const end = source.indexOf(');', start);
const old = JSON.parse(source.slice(start, end));
assert.equal(old.ready, false);
source = source.slice(0, start) + JSON.stringify(pins) + source.slice(end);
await fs.writeFile(pinFile, source);
const receipt = { observedAt: new Date().toISOString(), target: { sessionId, ...session.target }, sourceCommit: manifest.sourceCommit, imageId: session.container.imageId, pinsSha256: sha(source), backendTraceEnabledBeforeManualCalls: true, fixedSetupQualifications: '8/8', nativeSLOQualified: false, ports: session.ports, metadata: { tenantId: session.publicRuntime.tenantId, memorySpaceId: session.publicRuntime.memorySpaceId, agentId: session.publicRuntime.agentId, agentVersion: session.publicRuntime.agentVersion, definitionHash: session.publicRuntime.definitionHash } };
await fs.writeFile(path.join(qa, 'k26-native-ready.json'), JSON.stringify(receipt, null, 2) + '\n', { flag: 'wx' });
console.log(JSON.stringify({ ready: true, sessionId, target: session.target.name, id: session.target.id, ports: session.ports, traceEnabled: true }));
