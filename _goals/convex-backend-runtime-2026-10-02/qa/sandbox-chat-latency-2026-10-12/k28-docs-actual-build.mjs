import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { spawn, execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const qa = path.dirname(fileURLToPath(import.meta.url));
const website = '/Users/SaintNick/Documents/Cortex/worktrees/backend-runtime-docs';
const cwd = path.join(website, 'docs-site');
const pinned = '/Users/SaintNick/.codex/tmp/cortex-runtime-toolchain-20261005/node_modules/.bin';
const npm = '/Users/SaintNick/.codex/tmp/cortex-runtime-toolchain-20261005/node_modules/npm/bin/npm-cli.js';
assert.equal(process.version, 'v24.15.0');
const digest = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const files = execFileSync('git', ['diff', '--name-only', '--', 'docs-site/docs'], { cwd: website, encoding: 'utf8' }).trim().split('\n').filter(Boolean);
assert.equal(files.length, 10);
const hashes = Object.fromEntries(files.map(name => [name, digest(fs.readFileSync(path.join(website, name)))]));
const patch = execFileSync('git', ['diff', '--', 'docs-site/docs'], { cwd: website, maxBuffer: 1024 * 1024 });
fs.writeFileSync(path.join(qa, 'k28-website-documentation-handoff-actual-v2.patch'), patch, { flag: 'wx' });
const fd = fs.openSync(path.join(qa, 'docs-k28-actual-build-v2.log'), 'wx');
const startedAt = new Date().toISOString();
const result = await new Promise(resolve => {
  const child = spawn(process.execPath, [npm, 'run', 'build'], { cwd, env: { ...process.env, PATH: pinned + path.delimiter + process.env.PATH }, stdio: ['ignore', fd, fd] });
  child.once('error', error => resolve({ exitCode: null, error: error.code ?? error.message }));
  child.once('close', (exitCode, signal) => resolve({ exitCode, signal }));
});
fs.closeSync(fd);
const unchanged = Object.entries(hashes).every(([name, expected]) => digest(fs.readFileSync(path.join(website, name))) === expected);
const receipt = { repository: 'SaintNick1214/cortexmemory.dev', cwd, startedAt, endedAt: new Date().toISOString(), node: process.version, npm: '12.2.0', ...result, hashes, unchanged, patchSha256: digest(patch), browser: 'PENDING', published: false, committed: false };
fs.writeFileSync(path.join(qa, 'docs-k28-actual-build-v2.json'), JSON.stringify(receipt, null, 2) + '\n', { flag: 'wx' });
console.log(JSON.stringify({ ...result, unchanged, files: files.length, patchBytes: patch.length }));
if (result.exitCode !== 0 || !unchanged) process.exitCode = 1;
