/**
 * Environment file generator
 *
 * Generates .env.local and docker-compose files for init wizard.
 */

import type { WizardConfig } from "./types.js";
import pc from "picocolors";
import { appendRuntimeEnvironment } from "./backend-setup.js";
// Shared private environment loader; templates and SDK installers use the same selected configuration.
export { readSelectedGraphEnvironment } from "../graph/service.js";

/**
 * Generate .env.local file content based on wizard configuration
 */
export function generateEnvFile(config: WizardConfig): string {
  let env = `# Cortex Memory SDK Configuration
# Generated by cortex init on ${new Date().toISOString()}

# =============================================================================
# Convex Configuration
# =============================================================================
`;

  // Add Convex configuration based on setup type
  if (config.convexSetupType === "local") {
    env += `# Local Development
LOCAL_CONVEX_URL=http://127.0.0.1:3210
LOCAL_CONVEX_DEPLOYMENT=anonymous:anonymous-${config.projectName}
CONVEX_URL=http://127.0.0.1:3210
`;
  } else {
    env += `# Convex Cloud
CONVEX_URL=${config.convexUrl || ""}
`;
    if (config.deployKey) {
      env += `CONVEX_DEPLOY_KEY=${config.deployKey}
`;
    }
  }

  if (config.graphEnabled && config.graphType !== "skip") {
    throw new Error(
      "GRAPH_SHARED_SERVICE_REQUIRED: call setupGraph; credentials are stored privately in .cortex/graph",
    );
  }

  env += "\n# Inference/embedding policies and optional graph workers are configured on the backend.\n# Supply host-issued JWTs via the runtime client auth callback; do not store them here.\n";

  return env;
}

/**
 * Write .env.local file to project
 *
 * Existing host bytes and credentials stay untouched. Only public runtime
 * endpoint metadata is appended; a differing endpoint requires review.
 */
export async function createEnvFile(
  projectPath: string,
  config: WizardConfig,
): Promise<void> {
  if (config.convexUrl) {
    await appendRuntimeEnvironment(projectPath, { CONVEX_URL: config.convexUrl, NEXT_PUBLIC_CONVEX_URL: config.convexUrl });
  }
  console.log(pc.green("   Preserved host environment and configured runtime endpoints"));
}

